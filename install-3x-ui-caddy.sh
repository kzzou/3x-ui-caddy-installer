}

read_existing_layout() {
    python3 - /etc/x-ui/x-ui.db "$DOMAIN" <<'PY'
import re
import sqlite3
import sys

db, domain = sys.argv[1:]
with sqlite3.connect("file:" + db + "?mode=ro", uri=True) as conn:
    settings = dict(conn.execute("SELECT key, value FROM settings"))
required = {"webListen": "127.0.0.1", "webPort": "2053", "subListen": "127.0.0.1",
            "subPort": "2096", "webDomain": domain, "subDomain": domain,
            "webCertFile": "", "webKeyFile": "", "subCertFile": "", "subKeyFile": ""}
if any(settings.get(key) != value for key, value in required.items()):
    raise SystemExit("已有监听地址、域名或 TLS 设置与旧脚本不符，请勿自动迁移。")
paths = [settings.get(key, "") for key in ("webBasePath", "subPath", "subJsonPath", "subClashPath")]
if len(set(paths)) != 4 or any(not re.fullmatch(r"/[a-zA-Z0-9_-]+/", p) for p in paths):
    raise SystemExit("已有访问路径不符合本脚本格式，拒绝覆盖。")
for key, path in zip(("subURI", "subJsonURI", "subClashURI"), paths[1:]):
    if settings.get(key) != "https://" + domain + path:
        raise SystemExit("公开订阅地址与域名不符，拒绝自动迁移。")
print("\n".join(path.rstrip("/") for path in paths))
PY
}

rollback_migration() {
    local failed=0
    log '回滚本次迁移，恢复数据库、Caddyfile 和服务状态。'
    # If the initial stop only partly succeeds, all configuration is untouched.
    # Restart original services without retrying the failed stop or writing DB.
    if (( MIGRATION_MUTATED == 0 )); then
        if [[ "$CADDY_WAS_ACTIVE" == active ]]; then systemctl start caddy || failed=1; fi
        if [[ "$XUI_WAS_ACTIVE" == active ]]; then systemctl start x-ui || failed=1; fi
        if (( failed )); then
            printf '配置未修改，但原服务未全部恢复，请查看 systemctl status x-ui caddy。\n' >&2
        fi
        return 0
    fi
    systemctl stop x-ui caddy || failed=1
    if (( failed )); then
        printf '无法停止服务，未覆盖正在使用的数据库。请使用备份手动恢复：%s\n' "$BACKUP_DIR" >&2
        return 0
    fi
    if (( MIGRATION_DB_READY )); then
        # Restore with SQLite's backup API, including any existing WAL state.
        python3 - "$BACKUP_DIR/x-ui.db" /etc/x-ui/x-ui.db <<'PY' || failed=1
import sqlite3
import sys
with sqlite3.connect(sys.argv[1]) as src, sqlite3.connect(sys.argv[2]) as dst:
    src.backup(dst)
PY
    fi
    cp -a "$BACKUP_DIR/Caddyfile" /etc/caddy/Caddyfile || failed=1
    if [[ -f "$BACKUP_DIR/node.json" ]]; then
        cp -a "$BACKUP_DIR/node.json" "$NODE_INFO" || failed=1
    else
        rm -f -- "$NODE_INFO" || failed=1
    fi
    if (( failed )); then
        printf '恢复文件失败，服务保持停止。请使用备份手动恢复：%s\n' "$BACKUP_DIR" >&2
        return 0
    fi
    if [[ "$CADDY_WAS_ACTIVE" == active ]]; then systemctl start caddy || failed=1; fi
    if [[ "$XUI_WAS_ACTIVE" == active ]]; then systemctl start x-ui || failed=1; fi
    if (( failed )); then
        printf '回滚有失败项，请查看服务日志并用备份恢复：%s\n' "$BACKUP_DIR" >&2
    fi
}

check_migration_ports() {
    python3 - "$1" <<'PY'
import json
from pathlib import Path
import re
import subprocess
import sys
import urllib.request

groups = {}
for service in ("x-ui", "caddy"):
    value = subprocess.check_output(["systemctl", "show", service, "-p", "ControlGroup", "--value"], text=True).strip()
    if value:
        groups[service] = value
for port, services in ((80, ("caddy",)), (443, ("caddy", "x-ui")),
                       (8443, ("caddy",)), (2019, ("caddy",))):
    for network in ("-ltnp", "-lunp"):
        output = subprocess.check_output(["ss", "-H", network, "sport = :" + str(port)], text=True)
        for line in output.splitlines():
            pids = re.findall(r"pid=(\d+)", line)
            if not pids:
                raise SystemExit("无法确认端口 %s 所属服务。" % port)
            for pid in pids:
                actual = [s.split(":", 2)[2] for s in Path("/proc/" + pid + "/cgroup").read_text().splitlines()]
                if not any(g == groups[s] or g.startswith(groups[s] + "/")
                           for s in services if s in groups for g in actual):
                    raise SystemExit("端口 %s 被本脚本服务以外的进程占用。" % port)
if subprocess.run(["systemctl", "is-active", "--quiet", "caddy"]).returncode == 0:
    client = urllib.request.build_opener(urllib.request.ProxyHandler({}))
    with client.open("http://127.0.0.1:2019/config/", timeout=5) as response:
        live = json.load(response)
    with open(sys.argv[1]) as file:
        if live != json.load(file):
            raise SystemExit("Caddy 实际运行配置与磁盘配置不同，拒绝覆盖。")
PY
}

migrate_existing() {
    local layout candidate match=0 xui_version
    local -a paths
    [[ -f /etc/x-ui/x-ui.db && -f /etc/caddy/Caddyfile && -f /etc/systemd/system/x-ui.service ]] || \
        die '--migrate 仅适用于本脚本安装的已有服务。'
    grep -qF 'Description=3x-ui panel (Caddy reverse proxy)' /etc/systemd/system/x-ui.service || \
        die 'x-ui 服务单元与本脚本不符。'
    xui_version=$(/usr/local/x-ui/x-ui -v)
    [[ "$xui_version" == "${XUI_VERSION#v}" || "$xui_version" == "$XUI_VERSION" ]] || \
        die "迁移只支持 $XUI_VERSION，当前版本：$xui_version"
    [[ -x "$XRAY_BINARY" ]] || die '未找到对应的 Xray 二进制。'
    layout=$(read_existing_layout) || die '无法读取兼容的旧安装配置。'
    mapfile -t paths <<< "$layout"
    PANEL_PATH=${paths[0]} SUB_PATH=${paths[1]} JSON_PATH=${paths[2]} CLASH_PATH=${paths[3]}
    WORK_DIR=$(mktemp -d /tmp/3x-ui-caddy.XXXXXXXX)
    trap cleanup EXIT
    trap 'exit 130' INT
    trap 'exit 143' TERM
    render_legacy_caddyfile > "$WORK_DIR/legacy.Caddyfile"
    render_caddyfile > "$WORK_DIR/Caddyfile"
    caddy adapt --config /etc/caddy/Caddyfile --adapter caddyfile > "$WORK_DIR/existing.json"
    for candidate in legacy.Caddyfile Caddyfile; do
        caddy adapt --config "$WORK_DIR/$candidate" --adapter caddyfile > "$WORK_DIR/candidate.json"
        if python3 - "$WORK_DIR/existing.json" "$WORK_DIR/candidate.json" <<'PY'
import json
import sys
with open(sys.argv[1]) as a, open(sys.argv[2]) as b:
    sys.exit(0 if json.load(a) == json.load(b) else 1)
PY
        then match=1; break; fi
    done
    (( match )) || die 'Caddyfile 含非本脚本的配置，拒绝覆盖其他站点。'
    caddy fmt --overwrite "$WORK_DIR/Caddyfile"
    caddy validate --config "$WORK_DIR/Caddyfile" --adapter caddyfile
    check_migration_ports "$WORK_DIR/existing.json"
    BACKUP_DIR=$(mktemp -d /root/3x-ui-caddy-backup.XXXXXXXX)
    cp -a /etc/caddy/Caddyfile "$BACKUP_DIR/Caddyfile"
    if [[ -f "$NODE_INFO" ]]; then cp -a "$NODE_INFO" "$BACKUP_DIR/node.json"; fi
    XUI_WAS_ACTIVE=$(systemctl is-active x-ui || true)
    CADDY_WAS_ACTIVE=$(systemctl is-active caddy || true)
    printf 'x-ui=%s\ncaddy=%s\n' "$XUI_WAS_ACTIVE" "$CADDY_WAS_ACTIVE" > "$BACKUP_DIR/service-state.txt"
    MIGRATION_STARTED=1
    systemctl stop x-ui caddy
    for candidate in 80 443 8443; do
        port_busy "$candidate" && die "停止服务后端口 $candidate 仍被占用，取消迁移。"
    done
    python3 - /etc/x-ui/x-ui.db "$BACKUP_DIR/x-ui.db" <<'PY'
import sqlite3
import sys
with sqlite3.connect(sys.argv[1]) as src, sqlite3.connect(sys.argv[2]) as dst:
    src.backup(dst)
PY
    MIGRATION_DB_READY=1
    MIGRATION_MUTATED=1
    configure_reality_inbound /etc/x-ui/x-ui.db "$DOMAIN" "$XRAY_BINARY" "$NODE_INFO"
    write_node_access
    install -o root -g caddy -m 640 "$WORK_DIR/Caddyfile" /etc/caddy/Caddyfile
    systemctl start caddy
    systemctl start x-ui
    wait_panel
    systemctl is-active --quiet x-ui caddy || die '迁移后服务未处于运行状态。'
    check_shared_listeners
    wait_public_https || die '迁移后 HTTPS 443 验证失败，将恢复原配置。'
    COMPLETE=1
    log '迁移完成：面板、订阅和 REALITY 节点现共用公网 TCP 443。'
    printf '面板：https://%s%s/\n节点：sudo cat %s\n备份：%s\n' "$DOMAIN" "$PANEL_PATH" "$NODE_INFO" "$BACKUP_DIR"
    printf '原管理员、访问路径和其他入站保持不变；其他入站原来开放的端口仍需单独管理。\n'
}

main() {
    local render=0 migrate=0 arch checksum item username password ready=0
    case "${1:-}" in
        -h|--help) usage; return 0 ;;
        --render) render=1; shift ;;
        --migrate) migrate=1; shift ;;
    esac
    (( $# <= 1 )) || die '只接受一个域名参数。'
    DOMAIN="${1:-}"
    if [[ -z "$DOMAIN" ]]; then
        [[ -t 0 ]] || die '请提供域名，例如：sudo bash install-3x-ui-caddy.sh panel.example.com'
        read -r -p '请输入面板域名或网址（例如 https://panel.example.com）：' DOMAIN
    fi
    DOMAIN=$(normalize_domain_input "$DOMAIN")
    validate_domain "$DOMAIN" || die '请输入有效域名或 http(s) 网址；不支持页面路径、查询参数或非 443 端口，中文域名请使用 punycode。'
    if (( render )); then
        PANEL_PATH=/panel-preview SUB_PATH=/sub-preview
        JSON_PATH=/json-preview CLASH_PATH=/clash-preview
        render_caddyfile
        return 0
    fi

    [[ $EUID -eq 0 ]] || die '请使用 root 或 sudo 运行。'
    [[ "$(uname -s)" == Linux ]] || die '安装目标必须为 Linux。'
    [[ -d /run/systemd/system ]] || die '需要正在运行的 systemd。'
    command -v flock >/dev/null || die '缺少 flock，请安装 util-linux。'
    exec 9>/run/lock/3x-ui-caddy-install.lock
    flock -n 9 || die '另一个安装任务正在运行。'
    # shellcheck disable=SC1091
    source /etc/os-release
    case "${ID:-}:${VERSION_ID:-}" in
        debian:*) [[ "${VERSION_ID%%.*}" =~ ^[0-9]+$ ]] && (( ${VERSION_ID%%.*} >= 12 )) || die '需要 Debian 12+。' ;;
        ubuntu:*) [[ "${VERSION_ID%%.*}" =~ ^[0-9]+$ ]] && (( ${VERSION_ID%%.*} >= 22 )) || die '需要 Ubuntu 22.04+。' ;;
        *) die '此脚本支持 Debian 12+ / Ubuntu 22.04+。' ;;
    esac
    case "$(uname -m)" in
        x86_64) arch=amd64; checksum=236b837627520f0c4ae4134dc6a34ea5e294b69e158879795fe8cd51c5f3582c ;;
        aarch64|arm64) arch=arm64; checksum=e93b7a6ba83bace11c5bf2192a15ae0eec24b1c02496567149fce0d223aba309 ;;
        *) die '当前只支持 amd64 / arm64。' ;;
    esac
    XRAY_BINARY="/usr/local/x-ui/bin/xray-linux-$arch"
    for item in $(compgen -e); do
        [[ "$item" != XUI_* ]] || die "请清除已有环境变量 $item 后重试。"
    done
    command -v ss >/dev/null || die '缺少 ss，请先安装 iproute2。'
    if (( migrate )); then
        migrate_existing
        return 0
    fi

    # Refuse existing state instead of treating a second run as an upgrade.
    for item in /usr/local/x-ui /etc/x-ui /usr/bin/x-ui /usr/local/bin/x-ui \
        /etc/default/x-ui /etc/sysconfig/x-ui /etc/conf.d/x-ui \
        /etc/caddy /root/3x-ui-caddy-access.txt "$NODE_INFO" \
        /etc/apt/sources.list.d/caddy-stable.list \
        /usr/share/keyrings/caddy-stable-archive-keyring.gpg; do
        [[ ! -e "$item" && ! -L "$item" ]] || die "检测到已有文件 $item。此脚本只用于全新安装。"
    done
    for item in x-ui caddy; do
        if command -v "$item" >/dev/null 2>&1 || \
            [[ "$(systemctl show "$item.service" -p LoadState --value)" != not-found ]]; then
            die "检测到已有 $item，停止以保护现有配置。"
        fi
    done
    for item in 80 443 2019 "$CADDY_TLS_PORT" "$PANEL_PORT" "$SUB_PORT"; do
        port_busy "$item" && die "端口 $item 已被占用，请先处理冲突。"
    done
    trap cleanup EXIT
    trap 'exit 130' INT
    trap 'exit 143' TERM
    WORK_DIR=$(mktemp -d /tmp/3x-ui-caddy.XXXXXXXX)

    update_system
    log '安装基础工具；下载固定版本的官方发行包并校验 SHA-256。'
    apt-get install -y ca-certificates curl gnupg debian-keyring \
        debian-archive-keyring apt-transport-https python3 tar openssl iproute2
    download "https://github.com/MHSanaei/3x-ui/releases/download/$XUI_VERSION/x-ui-linux-$arch.tar.gz" "$WORK_DIR/x-ui.tar.gz"
    printf '%s  %s\n' "$checksum" "$WORK_DIR/x-ui.tar.gz" | sha256sum --check --status || die '3x-ui 发行包校验失败。'
    tar -xzf "$WORK_DIR/x-ui.tar.gz" -C "$WORK_DIR"
    [[ -f "$WORK_DIR/x-ui/x-ui" && -d "$WORK_DIR/x-ui/bin" ]] || die '发行包结构不符合预期。'

    username="u$(openssl rand -hex 5)"
    password=$(openssl rand -hex 18)
    PANEL_PATH="/panel-$(openssl rand -hex 12)"
    SUB_PATH="/sub-$(openssl rand -hex 12)"
    JSON_PATH="/json-$(openssl rand -hex 12)"
    CLASH_PATH="/clash-$(openssl rand -hex 12)"
    install -d -m 700 /etc/x-ui
    mv "$WORK_DIR/x-ui" /usr/local/x-ui
    chmod 755 /usr/local/x-ui/x-ui
    find /usr/local/x-ui/bin -maxdepth 1 -type f -name 'xray-linux-*' -exec chmod 755 {} +
    [[ ! -f /usr/local/x-ui/x-ui.sh ]] || install -m 755 /usr/local/x-ui/x-ui.sh /usr/bin/x-ui
    export XUI_DB_FOLDER=/etc/x-ui XUI_DB_TYPE=sqlite
    (
        cd /usr/local/x-ui
        ./x-ui setting -username "$username" -password "$password" \
            -port "$PANEL_PORT" -listenIP 127.0.0.1 -webBasePath "${PANEL_PATH}/"
    ) > "$WORK_DIR/initialize.log" 2>&1
    configure_database /etc/x-ui/x-ui.db
    configure_reality_inbound /etc/x-ui/x-ui.db "$DOMAIN" "$XRAY_BINARY" "$NODE_INFO"
    write_node_access
    chmod 600 /etc/x-ui/x-ui.db

    cat > /root/3x-ui-caddy-access.txt <<EOF
3x-ui $XUI_VERSION + Caddy
面板：https://$DOMAIN${PANEL_PATH}/
用户名：$username
密码：$password
普通订阅：https://$DOMAIN${SUB_PATH}/<客户端订阅ID>
JSON 订阅：https://$DOMAIN${JSON_PATH}/<客户端订阅ID>
Clash 订阅：https://$DOMAIN${CLASH_PATH}/<客户端订阅ID>
面板监听：127.0.0.1:$PANEL_PORT
订阅监听：127.0.0.1:$SUB_PORT
Caddy HTTPS：127.0.0.1:$CADDY_TLS_PORT
REALITY 入站：公网 TCP 443（REALITY-443-Caddy）
节点与订阅导入信息：$NODE_INFO
EOF
    chmod 600 /root/3x-ui-caddy-access.txt

    cat > "$WORK_DIR/x-ui.service" <<'EOF'
[Unit]
Description=3x-ui panel (Caddy reverse proxy)
After=network-online.target
Wants=network-online.target

[Service]
Type=simple
User=root
WorkingDirectory=/usr/local/x-ui
Environment=XUI_DB_FOLDER=/etc/x-ui
Environment=XUI_DB_TYPE=sqlite
ExecStart=/usr/local/x-ui/x-ui
Restart=on-failure
RestartSec=5s
UMask=0077

[Install]
WantedBy=multi-user.target
EOF
    install -m 644 "$WORK_DIR/x-ui.service" /etc/systemd/system/x-ui.service
    XUI_OWNED=1
    systemctl daemon-reload

    log '从 Caddy 官方软件源安装；生成 HTTPS 反向代理配置。'
    download 'https://dl.cloudsmith.io/public/caddy/stable/gpg.key' "$WORK_DIR/caddy.asc"
    gpg --batch --yes --dearmor --output "$WORK_DIR/caddy.gpg" "$WORK_DIR/caddy.asc"
    install -m 644 "$WORK_DIR/caddy.gpg" /usr/share/keyrings/caddy-stable-archive-keyring.gpg
    download 'https://dl.cloudsmith.io/public/caddy/stable/debian.deb.txt' "$WORK_DIR/caddy.list"
    install -m 644 "$WORK_DIR/caddy.list" /etc/apt/sources.list.d/caddy-stable.list
    apt-get update
    # Prevent the package post-install hook from exposing its default site.
    CADDY_CONFIGURED=1
    systemctl mask caddy.service
    CADDY_MASKED=1
    apt-get install -y caddy
    cp -a /etc/caddy/Caddyfile "$WORK_DIR/Caddyfile.package-default"
    render_caddyfile > "$WORK_DIR/Caddyfile"
    caddy fmt --overwrite "$WORK_DIR/Caddyfile"
    caddy validate --config "$WORK_DIR/Caddyfile" --adapter caddyfile
    install -o root -g caddy -m 640 "$WORK_DIR/Caddyfile" /etc/caddy/Caddyfile

    log '启动本机 Caddy HTTPS 和公网 REALITY 443 入站。'
    systemctl unmask caddy.service
    CADDY_MASKED=0
    systemctl enable --now caddy
    systemctl enable --now x-ui
    wait_panel
    check_shared_listeners
    verify_login "$username" "$password"
    systemctl is-active --quiet x-ui caddy || die '服务未处于运行状态。'

    ready=0
    if wait_public_https; then ready=1; fi
    check_shared_listeners
    systemctl is-active --quiet x-ui caddy || die '等待证书期间服务停止，安装未完成。'
    if (( ready == 0 )) && curl --noproxy '*' -fsS --connect-timeout 2 --max-time 5 \
        --connect-to "$DOMAIN:443:127.0.0.1:$CADDY_TLS_PORT" "https://$DOMAIN${PANEL_PATH}/" -o /dev/null 2>/dev/null; then
        die 'Caddy HTTPS 已就绪，但 REALITY 443 回落验证失败。'
    fi
    # TLS pending is recoverable: leave Caddy running so ACME can retry.
    COMPLETE=1
    if (( ready )); then
        log '安装完成：面板、订阅和 REALITY 入站共用公网 TCP 443。'
    else
        log '服务已安装且内部端口已绑定本机；HTTPS 尚未验证成功。'
        printf '请检查域名 A/AAAA、云安全组和 TCP 80/443；Caddy 会自动重试签发证书。\n'
    fi
    printf '\n面板：https://%s%s/\n' "$DOMAIN" "$PANEL_PATH"
    printf '用户名和密码：sudo cat /root/3x-ui-caddy-access.txt\n'
    printf '节点及订阅导入信息：sudo cat %s\n' "$NODE_INFO"
    printf '配置：/etc/caddy/Caddyfile\n日志：journalctl -u x-ui -u caddy -n 80 --no-pager\n'
    printf '仍需在外部设备验证域名可访问、2053/2096/8443 不可直连。\n'
    if [[ -f /var/run/reboot-required ]]; then
        printf '系统更新提示需要重启，请在安装完成后择机手动重启服务器。\n'
    fi
    (( ready )) || return 2
}

