normalize_domain_input() {
    local input="$1"
    local markdown_link='^\[[^][]+\]\((https?://[^[:space:]()]*)\)$'
    # Accept pasted browser addresses, including links copied from chat.
    input="${input#"${input%%[![:space:]]*}"}"
    input="${input%"${input##*[![:space:]]}"}"
    input="${input,,}"
    if [[ "$input" =~ $markdown_link ]]; then
        input="${BASH_REMATCH[1]}"
    fi
    case "$input" in
        https://*) input="${input#https://}" ;;
        http://*) input="${input#http://}" ;;
    esac
    input="${input%/}"
    input="${input%:443}"
    printf '%s' "$input"
}

validate_domain() {
    local domain="$1" label
    [[ ${#domain} -le 253 && "$domain" == *.* ]] || return 1
    [[ "$domain" =~ ^[a-z0-9.-]+$ && ! "$domain" =~ ^[0-9.]+$ ]] || return 1
    [[ "$domain" != *. && "$domain" != *..* ]] || return 1
    local -a labels
    IFS=. read -r -a labels <<< "$domain"
    for label in "${labels[@]}"; do
        [[ ${#label} -ge 1 && ${#label} -le 63 ]] || return 1
        [[ "$label" != -* && "$label" != *- ]] || return 1
    done
    [[ ${#label} -ge 2 && ! "$label" =~ ^[0-9]+$ ]]
}

render_legacy_caddyfile() {
    cat <<EOF
# Generated by install-3x-ui-caddy.sh
$DOMAIN {
    encode zstd gzip
    header -Server
    header Strict-Transport-Security "max-age=31536000"

    # Preserve the base path; handle_path would strip it and break 3x-ui.
    redir $PANEL_PATH ${PANEL_PATH}/ 308
    handle ${PANEL_PATH}/* {
        reverse_proxy 127.0.0.1:$PANEL_PORT {
            # 3x-ui's HTTP backend does not mark its session cookies Secure.
            header_down Set-Cookie "^(.*)$" "\$1; Secure"
        }
    }

    @subscription path ${SUB_PATH}/* ${JSON_PATH}/* ${CLASH_PATH}/*
    handle @subscription {
        reverse_proxy 127.0.0.1:$SUB_PORT
    }

    handle {
        respond "Not Found" 404
    }
}
EOF
}

render_caddyfile() {
    cat <<EOF
# Generated by install-3x-ui-caddy.sh
{
    auto_https disable_redirects
    servers {
        protocols h1 h2
    }
}

# HTTP-01 certificates are renewed on public port 80, independently of Xray.
http://$DOMAIN {
    redir https://$DOMAIN{uri} 308
}

# Xray owns public TCP 443 and forwards ordinary TLS to this loopback listener.
https://$DOMAIN:$CADDY_TLS_PORT {
    bind 127.0.0.1
    tls {
        issuer acme {
            disable_tlsalpn_challenge
        }
    }
    encode zstd gzip
    header -Server
    header Strict-Transport-Security "max-age=31536000"
    redir $PANEL_PATH ${PANEL_PATH}/ 308
    handle ${PANEL_PATH}/* {
        reverse_proxy 127.0.0.1:$PANEL_PORT {
            header_down Set-Cookie "^(.*)$" "\$1; Secure"
        }
    }
    @subscription path ${SUB_PATH}/* ${JSON_PATH}/* ${CLASH_PATH}/*
    handle @subscription {
        reverse_proxy 127.0.0.1:$SUB_PORT
    }
    handle {
        respond "Not Found" 404
    }
}
EOF
}

# CLI initialization creates the schema and hashes the random credentials.
# Subscription settings have no equivalent CLI flags in this pinned version.
# Write them in one parameterized transaction while the service is stopped.
configure_database() {
    python3 - "$1" "$DOMAIN" "$PANEL_PORT" "$SUB_PORT" \
        "$PANEL_PATH" "$SUB_PATH" "$JSON_PATH" "$CLASH_PATH" <<'PY'
import sqlite3
import sys
from pathlib import Path

db, domain, panel_port, sub_port, panel, sub, json_path, clash = sys.argv[1:]
if not Path(db).is_file():
    raise SystemExit("3x-ui 没有创建数据库，停止安装。")
settings = {
    "webListen": "127.0.0.1", "webPort": panel_port,
    "webDomain": domain, "webBasePath": panel + "/",
    "webCertFile": "", "webKeyFile": "",
    "trustedProxyCIDRs": "127.0.0.1/32,::1/128",
    "subEnable": "true", "subListen": "127.0.0.1", "subPort": sub_port,
    "subDomain": domain, "subCertFile": "", "subKeyFile": "",
    "subPath": sub + "/", "subURI": "https://" + domain + sub + "/",
    "subJsonEnable": "true", "subJsonPath": json_path + "/",
    "subJsonURI": "https://" + domain + json_path + "/",
    "subClashEnable": "true", "subClashPath": clash + "/",
    "subClashURI": "https://" + domain + clash + "/",
}
with sqlite3.connect(db) as conn:
    columns = {row[1] for row in conn.execute("PRAGMA table_info(settings)")}
    if not {"key", "value"} <= columns:
        raise SystemExit("数据库结构不兼容，停止安装。")
    if conn.execute("SELECT count(*) FROM users").fetchone()[0] != 1:
        raise SystemExit("初始管理员数量异常，停止安装。")
    for key, value in settings.items():
        conn.execute("DELETE FROM settings WHERE key = ?", (key,))
        conn.execute("INSERT INTO settings (key, value) VALUES (?, ?)", (key, value))
    actual = dict(conn.execute("SELECT key, value FROM settings"))
    if any(actual.get(key) != value for key, value in settings.items()):
        raise SystemExit("数据库设置回读失败。")
PY
}

configure_reality_inbound() {
    local db=${1:?database path required}
    local domain=${2:?domain required}
    local xray_binary=${3:?xray binary required}
    local output_json=${4:?output JSON path required}

    [[ -f "$db" ]] || { printf '错误：3x-ui 数据库不存在：%s\n' "$db" >&2; return 1; }
    [[ -x "$xray_binary" ]] || { printf '错误：Xray 不可执行：%s\n' "$xray_binary" >&2; return 1; }
    command -v python3 >/dev/null 2>&1 || { printf '错误：缺少 python3。\n' >&2; return 1; }

    # The Python transaction keeps the legacy JSON fields and v3.8 normalized
    # client tables consistent. Xray output is captured in memory; private keys
    # are never printed or written to the public result file.
    umask 077
    python3 - "$db" "$domain" "$xray_binary" "$output_json" <<'PY'
import json
import os
import re
import secrets
import sqlite3
import subprocess
import sys
import time
import urllib.parse
import uuid
from pathlib import Path

DB, DOMAIN, XRAY, OUTPUT = sys.argv[1:]
REMARK = "REALITY-443-Caddy"
PORT = 443
TARGET = "127.0.0.1:8443"
FLOW = "xtls-rprx-vision"


def fail(message):
    raise SystemExit("错误：" + message)


def parse_keypair(text):
    private_key = ""
    public_key = ""
    for line in text.splitlines():
        match = re.match(r"\s*([^:]+?)\s*:\s*(\S+)\s*$", line)
        if not match:
            continue
        label = re.sub(r"[^a-z]", "", match.group(1).lower())
        value = match.group(2)
        if label in {"privatekey", "private"}:
            private_key = value
        elif label in {"publickey", "public", "password", "passwordpublickey"}:
            public_key = value
    return private_key, public_key


def valid_key(value):
    return bool(re.fullmatch(r"[A-Za-z0-9_-]{40,48}={0,2}", value or ""))


def run_x25519(private_key=None):
    command = [XRAY, "x25519"]
    if private_key:
        command += ["-i", private_key]
    try:
        proc = subprocess.run(command, stdout=subprocess.PIPE, stderr=subprocess.PIPE,
                              text=True, timeout=15, check=False)
    except (OSError, subprocess.SubprocessError):
        fail("Xray x25519 执行失败或超时。")
    if proc.returncode != 0:
        fail("Xray x25519 执行失败。")
    generated_private, generated_public = parse_keypair(proc.stdout)
    if private_key:
        generated_private = private_key
    if not valid_key(generated_private) or not valid_key(generated_public):
        fail("无法解析 Xray x25519 输出的密钥对。")
    return generated_private, generated_public


def columns(conn, table):
    return {row[1] for row in conn.execute(f'PRAGMA table_info("{table}")')}


def require_columns(conn, table, required):
    actual = columns(conn, table)
    missing = sorted(set(required) - actual)
    if missing:
        fail(f"3x-ui v3.8.0 数据库结构不兼容：{table} 缺少 {', '.join(missing)}")
    return actual


def insert_known(conn, table, values, actual_columns):
    selected = [(key, value) for key, value in values.items() if key in actual_columns]
    names = ", ".join(f'"{key}"' for key, _ in selected)
    placeholders = ", ".join("?" for _ in selected)
    conn.execute(f'INSERT INTO "{table}" ({names}) VALUES ({placeholders})',
                 tuple(value for _, value in selected))


def json_object(raw, label):
    try:
        value = json.loads(raw)
    except (TypeError, json.JSONDecodeError):
        fail(f"已有 {REMARK} 的 {label} 不是有效 JSON，为避免损坏已停止。")
    if not isinstance(value, dict):
        fail(f"已有 {REMARK} 的 {label} 结构无效。")
    return value


def valid_uuid(value):
    try:
        uuid.UUID(value)
        return True
    except (ValueError, TypeError, AttributeError):
        return False


db_path = Path(DB)
if not db_path.is_file():
    fail("3x-ui 数据库不存在。")

conn = sqlite3.connect(DB, timeout=15, isolation_level=None)
conn.row_factory = sqlite3.Row
try:
    inbound_cols = require_columns(conn, "inbounds", {
        "id", "user_id", "up", "down", "total", "remark", "enable",
        "expiry_time", "listen", "port", "protocol", "settings",
        "stream_settings", "tag", "sniffing",
    })
    client_cols = require_columns(conn, "clients", {
        "id", "email", "sub_id", "uuid", "flow", "enable", "created_at", "updated_at",
    })
    link_cols = require_columns(conn, "client_inbounds", {
        "client_id", "inbound_id", "flow_override", "created_at",
    })
    traffic_cols = require_columns(conn, "client_traffics", {
        "id", "inbound_id", "enable", "email", "up", "down", "expiry_time", "total",
    })
    require_columns(conn, "users", {"id"})

    conn.execute("BEGIN IMMEDIATE")
    owned = conn.execute("SELECT * FROM inbounds WHERE remark = ? ORDER BY id", (REMARK,)).fetchall()
    if len(owned) > 1:
        fail(f"发现多个同名入站 {REMARK}，请先在面板中处理。")
    current = owned[0] if owned else None
    current_id = current["id"] if current else -1
    conflict = conn.execute(
        "SELECT id, remark, protocol FROM inbounds WHERE port = ? AND id <> ? ORDER BY id LIMIT 1",
        (PORT, current_id),
    ).fetchone()
    if conflict:
        fail(f"TCP 443 已被其他 3x-ui 入站占用（ID {conflict['id']}, {conflict['remark'] or conflict['protocol']}）。")

    if current:
        if current["protocol"] != "vless":
            fail(f"已有同名入站的协议不是 VLESS，拒绝覆盖。")
        stream = json_object(current["stream_settings"], "streamSettings")
        if stream.get("security") != "reality" or stream.get("network") not in {"tcp", "raw"}:
            fail(f"已有同名入站不是 TCP/RAW + REALITY，拒绝覆盖。")
        reality = stream.get("realitySettings")
        if not isinstance(reality, dict):
            fail("已有同名入站缺少 realitySettings。")
        private_key = reality.get("privateKey", "")
        if not valid_key(private_key):
            fail("已有同名入站的 REALITY 私钥无效，拒绝重置身份。")
        client_hints = reality.get("settings")
        if not isinstance(client_hints, dict):
            client_hints = {}
        # Derive from the existing private key: stale public hints must not
        # silently produce an unusable import link. This does not rotate keys.
        _, public_key = run_x25519(private_key)
        short_ids = reality.get("shortIds")
        if (not isinstance(short_ids, list) or not short_ids
                or any(not isinstance(s, str) or not re.fullmatch(r"(?:[0-9a-fA-F]{2}){0,8}", s) for s in short_ids)
                or not short_ids[0]):
            fail("已有同名入站的 REALITY shortId 无效，拒绝重置身份。")
        short_id = str(short_ids[0]).lower()

        # Normalized tables are authoritative in 3x-ui v3.8.0. Pick the first
        # valid attached client for output while preserving every client/link.
        attached = conn.execute(
            "SELECT c.id, c.email, c.sub_id, c.uuid, c.enable, ci.flow_override "
            "FROM client_inbounds ci JOIN clients c ON c.id = ci.client_id "
            "WHERE ci.inbound_id = ? ORDER BY c.id",
            (current_id,),
        ).fetchall()
        selected = next((row for row in attached
                         if row["enable"] and row["email"] and row["sub_id"] and valid_uuid(row["uuid"])
                         and row["flow_override"] == FLOW), None)
        if selected is None:
            fail("已有同名入站没有启用 xtls-rprx-vision 的有效已关联客户端，拒绝重置身份。")
        client_uuid, email, sub_id = selected["uuid"], selected["email"], selected["sub_id"]

        # Repair only the routing/public hints the installer owns. Keep keys,
        # short IDs, all clients, counters and unrelated stream options intact.
        stream["network"] = "tcp"
        stream["security"] = "reality"
        reality["target"] = TARGET
        reality.pop("dest", None)
        reality["xver"] = 0
        reality["serverNames"] = [DOMAIN]
        client_hints.update({
            "publicKey": public_key, "fingerprint": "chrome",
            "serverName": DOMAIN, "spiderX": client_hints.get("spiderX") or "/",
        })
        reality["settings"] = client_hints
        stream["realitySettings"] = reality
        conn.execute(
            "UPDATE inbounds SET listen = ?, port = ?, enable = 1, stream_settings = ? WHERE id = ?",
            ("0.0.0.0", PORT, json.dumps(stream, separators=(",", ":")), current_id),
        )
        inbound_id = current_id
    else:
        private_key, public_key = run_x25519()
        short_id = secrets.token_hex(8)
        client_uuid = str(uuid.uuid4())
        sub_id = secrets.token_urlsafe(16)
        while True:
            email = "reality-" + secrets.token_hex(5)
            if conn.execute("SELECT 1 FROM clients WHERE email = ?", (email,)).fetchone() is None:
                break
        now = int(time.time() * 1000)
        client = {
            "id": client_uuid, "flow": FLOW, "email": email, "limitIp": 0,
            "totalGB": 0, "expiryTime": 0, "enable": True, "tgId": 0,
            "subId": sub_id, "comment": "", "reset": 0,
            "created_at": now, "updated_at": now,
        }
        settings = {"clients": [client], "decryption": "none", "encryption": "none", "fallbacks": []}
        stream = {
            "network": "tcp", "security": "reality",
            "tcpSettings": {"acceptProxyProtocol": False, "header": {"type": "none"}},
            "realitySettings": {
                "show": False, "xver": 0, "target": TARGET, "serverNames": [DOMAIN],
                "privateKey": private_key, "minClientVer": "", "maxClientVer": "",
                "maxTimediff": 0, "shortIds": [short_id], "mldsa65Seed": "",
                "settings": {"publicKey": public_key, "fingerprint": "chrome",
                             "serverName": DOMAIN, "spiderX": "/", "mldsa65Verify": ""},
            },
        }
        user_row = conn.execute("SELECT id FROM users ORDER BY id LIMIT 1").fetchone()
        if user_row is None:
            fail("3x-ui 数据库中没有管理员，无法创建入站。")
        while True:
            tag = "inbound-443-reality-" + secrets.token_hex(4)
            if conn.execute("SELECT 1 FROM inbounds WHERE tag = ?", (tag,)).fetchone() is None:
                break
        inbound_values = {
            "user_id": user_row["id"], "up": 0, "down": 0, "total": 0, "remark": REMARK,
            "sub_sort_index": 1, "enable": 1, "expiry_time": 0, "traffic_reset": "never",
            "traffic_reset_day": 1, "last_traffic_reset_time": 0,
            "listen": "0.0.0.0", "port": PORT, "protocol": "vless",
            "settings": json.dumps(settings, separators=(",", ":")),
            "stream_settings": json.dumps(stream, separators=(",", ":")),
            "tag": tag, "sniffing": json.dumps({"enabled": False}, separators=(",", ":")),
            "share_addr_strategy": "node", "share_addr": "", "disable_flow": 0,
            "origin_node_guid": "",
        }
        insert_known(conn, "inbounds", inbound_values, inbound_cols)
        inbound_id = conn.execute("SELECT last_insert_rowid()").fetchone()[0]

        client_values = {
            "email": email, "sub_id": sub_id, "uuid": client_uuid, "password": "",
            "auth": "", "flow": FLOW, "security": "", "reverse": "",
            "wg_private_key": "", "wg_public_key": "", "wg_allowed_ips": "",
            "wg_pre_shared_key": "", "wg_keep_alive": 0, "wg_forwarded_ports": "",
            "secret": "", "ad_tag": "", "limit_ip": 0, "limit_hwid": 0,
            "total_gb": 0, "expiry_time": 0, "enable": 1, "tg_id": 0,
            "group_name": "", "comment": "", "reset": 0, "reset_day": 0,
            "reset_max": 0, "traffic_reset": "never", "traffic_reset_day": 1,
            "created_at": now, "updated_at": now, "sync_orphaned_at": 0,
        }
        insert_known(conn, "clients", client_values, client_cols)
        client_id = conn.execute("SELECT last_insert_rowid()").fetchone()[0]
        insert_known(conn, "client_inbounds", {
            "client_id": client_id, "inbound_id": inbound_id,
            "flow_override": FLOW, "created_at": now,
        }, link_cols)
        insert_known(conn, "client_traffics", {
            "inbound_id": inbound_id, "enable": 1, "email": email,
            "up": 0, "down": 0, "expiry_time": 0, "total": 0, "reset": 0,
            "reset_day": 0, "reset_max": 0, "reset_count": 0,
            "last_online": 0, "last_sub_fetch": 0,
        }, traffic_cols)

    # Verify the identity mapping before committing. This catches partial or
    # schema-surprise writes while rollback is still possible.
    check = conn.execute(
        "SELECT i.port, i.protocol, c.uuid, c.sub_id, ci.flow_override, t.up, t.down "
        "FROM inbounds i JOIN client_inbounds ci ON ci.inbound_id = i.id "
        "JOIN clients c ON c.id = ci.client_id "
        "LEFT JOIN client_traffics t ON t.inbound_id = i.id AND t.email = c.email "
        "WHERE i.id = ? AND c.email = ?",
        (inbound_id, email),
    ).fetchone()
    if not check or check["port"] != PORT or check["protocol"] != "vless" or check["uuid"] != client_uuid:
        fail("REALITY 入站数据库回读验证失败。")
    conn.execute("COMMIT")
except BaseException:
    if conn.in_transaction:
        conn.execute("ROLLBACK")
    raise
finally:
    conn.close()

query = urllib.parse.urlencode({
    "type": "tcp", "security": "reality", "pbk": public_key,
    "fp": "chrome", "sni": DOMAIN, "sid": short_id,
    "spx": "/", "flow": FLOW,
})
vless_uri = f"vless://{client_uuid}@{DOMAIN}:{PORT}?{query}#{urllib.parse.quote(REMARK)}"
result = {
    "inbound_id": inbound_id, "uuid": client_uuid, "public_key": public_key,
    "short_id": short_id, "server_name": DOMAIN, "port": PORT,
    "email": email, "sub_id": sub_id, "vless_uri": vless_uri,
}
output_path = Path(OUTPUT)
output_path.parent.mkdir(parents=True, exist_ok=True)
temporary = output_path.with_name(output_path.name + ".tmp-" + secrets.token_hex(4))
try:
    fd = os.open(temporary, os.O_WRONLY | os.O_CREAT | os.O_EXCL, 0o600)
    with os.fdopen(fd, "w", encoding="utf-8") as handle:
        json.dump(result, handle, ensure_ascii=False, indent=2)
        handle.write("\n")
        handle.flush()
        os.fsync(handle.fileno())
    os.replace(temporary, output_path)
    os.chmod(output_path, 0o600)
finally:
    try:
        temporary.unlink()
    except FileNotFoundError:
        pass
PY
}

verify_login() {
    python3 - "$DOMAIN" "$PANEL_PORT" "$PANEL_PATH" "$1" "$2" <<'PY'
import http.cookiejar
import json
import sys
import urllib.parse
import urllib.request

domain, port, path, username, password = sys.argv[1:]
client = urllib.request.build_opener(
    urllib.request.ProxyHandler({}),
    urllib.request.HTTPCookieProcessor(http.cookiejar.CookieJar()),
)
base = "http://127.0.0.1:" + port + path
req = urllib.request.Request(base + "/csrf-token", headers={"Host": domain})
with client.open(req, timeout=10) as response:
    token = json.load(response)["obj"]
payload = urllib.parse.urlencode({"username": username, "password": password}).encode()
req = urllib.request.Request(base + "/login", data=payload,
                             headers={"Host": domain, "X-CSRF-Token": token})
with client.open(req, timeout=10) as response:
    if json.load(response).get("success") is not True:
        raise SystemExit("随机管理员凭据验证失败。")
print("随机管理员凭据验证通过。")
PY
}

cleanup() {
    local status=$?
    trap - EXIT
    if (( status != 0 && COMPLETE == 0 )); then
        if (( MIGRATION_STARTED )); then
            rollback_migration
            printf '\n迁移失败，已尝试恢复原配置和服务状态。备份：%s\n' "$BACKUP_DIR" >&2
            exit "$status"
        fi
        if (( XUI_OWNED )); then
            systemctl disable --now x-ui >/dev/null 2>&1 || true
        fi
        if (( CADDY_CONFIGURED )); then
            systemctl disable --now caddy >/dev/null 2>&1 || true
        fi
        if (( CADDY_MASKED )); then
            systemctl unmask caddy >/dev/null 2>&1 || true
        fi
        printf '\n安装未完成。已停用本次配置的服务；文件和日志保留以便排查。\n' >&2
        printf '查看日志：journalctl -u x-ui -u caddy -n 80 --no-pager\n' >&2
        [[ -z "$WORK_DIR" ]] || printf '本次工作目录：%s\n' "$WORK_DIR" >&2
    elif [[ -n "$WORK_DIR" ]]; then
        rm -rf -- "$WORK_DIR"
    fi
    exit "$status"
}

port_busy() {
    [[ -n "$(ss -H -ltn "sport = :$1")" || -n "$(ss -H -lun "sport = :$1")" ]]
}

check_loopback() {
    local port="$1" addresses
    addresses=$(ss -H -ltn "sport = :$port" | awk '{print $4}')
    [[ "$addresses" == "127.0.0.1:$port" ]] || \
        die "端口 $port 未严格绑定 127.0.0.1，已拒绝完成安装。"
}

download() {
    curl --fail --location --silent --show-error --retry 3 \
        --connect-timeout 15 --max-time 600 --proto '=https' --proto-redir '=https' \
        --output "$2" "$1"
}

update_system() {
    log '更新软件源索引；任一软件源更新失败时停止安装。'
    export DEBIAN_FRONTEND=noninteractive
    apt-get -o APT::Update::Error-Mode=any update
    if [[ "$ID" == ubuntu ]]; then
        log '升级 Ubuntu 已安装的软件包，保留已有配置文件。'
        apt-get -o DPkg::Lock::Timeout=120 \
            -o Dpkg::Options::=--force-confdef \
            -o Dpkg::Options::=--force-confold upgrade -y
    fi
}

wait_panel() {
    local attempt
    for attempt in {1..30}; do
        if curl --noproxy '*' -fsS --max-time 2 -H "Host: $DOMAIN" \
            "http://127.0.0.1:$PANEL_PORT${PANEL_PATH}/" -o /dev/null 2>/dev/null && \
            [[ -n "$(ss -H -ltn "sport = :$SUB_PORT")" && -n "$(ss -H -ltn 'sport = :443')" ]]; then
            return 0
        fi
        sleep 1
    done
    die '面板、订阅或 REALITY 443 入站未正常启动。'
}

check_shared_listeners() {
    check_loopback "$PANEL_PORT"
    check_loopback "$SUB_PORT"
    check_loopback "$CADDY_TLS_PORT"
    local listeners
    listeners=$(ss -H -ltnp 'sport = :443')
    [[ "$listeners" == *xray* && "$listeners" != *caddy* ]] || die '公网 TCP 443 未由 Xray 独占。'
}

wait_public_https() {
    local attempt
    log '验证公网 443 → REALITY → Caddy → 面板，等待证书最多约 90 秒。'
    for attempt in {1..18}; do
        if curl --noproxy '*' -fsS --connect-timeout 2 --max-time 3 \
            --resolve "$DOMAIN:443:127.0.0.1" "https://$DOMAIN${PANEL_PATH}/" -o /dev/null 2>/dev/null; then
            return 0
        fi
        sleep 2
    done
    return 1
}

write_node_access() {
    # Public key and UUID are sufficient for importing; the private key stays in DB.
    python3 - "$NODE_INFO" "$DOMAIN" "$SUB_PATH" <<'PY'
import json
